import pytest

from steward.standards.ai_trace import check_no_ai_trace
from tests.standards.builders import commit, merged_pr, snapshot

NAMES = ("claude", "anthropic", "codex", "openai", "gemini", "copilot", "chatgpt")


def _no_names(text: str) -> bool:
    return not any(name in text.lower() for name in NAMES)


def test_clean_history_has_no_findings() -> None:
    assert check_no_ai_trace(snapshot()) == []


@pytest.mark.parametrize(
    "message",
    [
        "feat: x\n\nCo-authored-by: Claude <noreply@anthropic.com>",
        "fix: y\n\nCo-Authored-By: GitHub Copilot <copilot@github.com>",
        "docs: z\n\nGenerated with Codex",
        "chore: w\n\n🤖 Generated by ChatGPT",
    ],
)
def test_attribution_in_a_commit_is_reported_without_naming_the_assistant(message: str) -> None:
    findings = check_no_ai_trace(snapshot(commits=[commit(message=message)]))
    assert [f.rule for f in findings] == ["ai-trace"]
    assert _no_names(findings[0].detail)
    assert "commit/a1b2c3d4" in findings[0].detail


def test_attribution_in_a_pr_body_is_reported() -> None:
    pr = merged_pr(body="Closes #1\n\nGenerated with Gemini")
    findings = check_no_ai_trace(snapshot(merged_prs=[pr]))
    assert [f.rule for f in findings] == ["ai-trace"]
    assert _no_names(findings[0].detail)


@pytest.mark.parametrize(
    "branch",
    ["claude/fix", "codex/x", "copilot/y", "cursor/z", "gemini/a", "openai/b", "ai/c"],
)
def test_ai_prefixed_branch_is_reported(branch: str) -> None:
    findings = check_no_ai_trace(snapshot(merged_prs=[merged_pr(head_ref=branch)]))
    assert [f.rule for f in findings] == ["ai-trace"]
    assert _no_names(findings[0].detail)


@pytest.mark.parametrize(
    "message",
    ["Use the OpenAI API for replies", "Add a Gemini model option", "Rename aid/ helper"],
)
def test_plain_mentions_are_not_traces(message: str) -> None:
    pr = merged_pr(title=message, head_ref="feature/openai-client")
    assert check_no_ai_trace(snapshot(commits=[commit(message=message)], merged_prs=[pr])) == []
